# Helper Data Functions
def fetch_tickets():
    conn = get_connection()
    df = pd.read_sql_query("SELECT * FROM compliance_tickets ORDER BY created_at DESC", conn)
    conn.close()
    return df

def fetch_audit_logs():
    conn = get_connection()
    df = pd.read_sql_query("SELECT * FROM compliance_audit ORDER BY id DESC", conn)
    conn.close()
    return df

def fetch_queue():
    conn = get_connection()
    df = pd.read_sql_query("SELECT * FROM document_queue ORDER BY id DESC", conn)
    conn.close()
    return df


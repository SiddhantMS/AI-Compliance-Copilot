if nav_view == "🎟️ Compliance Tickets":
    st.markdown('<div class="main-header">Compliance Tickets</div>', unsafe_allow_html=True)
    st.markdown('<div class="sub-header">Actionable compliance tickets generated by 3-agent LangGraph workflow</div>', unsafe_allow_html=True)

    df_tickets = fetch_tickets()

    if df_tickets.empty:
        st.warning("No compliance tickets found in SQLite database. Run `python run_pipeline.py` to process queued circulars.")
    else:
        # Metrics Top Bar
        col1, col2, col3, col4 = st.columns(4)
        high_count = len(df_tickets[df_tickets["priority"].str.contains("HIGH", na=False)])
        med_count = len(df_tickets[df_tickets["priority"].str.contains("MEDIUM", na=False)])
        low_count = len(df_tickets[df_tickets["priority"].str.contains("LOW", na=False)])

        with col1:
            st.metric("Total Tickets", len(df_tickets))
        with col2:
            st.metric("High Priority (P1)", high_count)
        with col3:
            st.metric("Medium Priority (P2)", med_count)
        with col4:
            st.metric("Low Priority (P3)", low_count)

        st.markdown("---")
        
        # Filter controls
        reg_filter = st.multiselect("Filter by Regulator", options=df_tickets["regulator"].unique(), default=df_tickets["regulator"].unique())
        prio_filter = st.multiselect("Filter by Priority", options=df_tickets["priority"].unique(), default=df_tickets["priority"].unique())

        filtered_df = df_tickets[
            (df_tickets["regulator"].isin(reg_filter)) &
            (df_tickets["priority"].isin(prio_filter))
        ]

        for idx, row in filtered_df.iterrows():
            priority_str = row["priority"]
            badge_class = "badge-high" if "HIGH" in priority_str else ("badge-medium" if "MEDIUM" in priority_str else "badge-low")
            
            with st.expander(f"📌 [{row['ticket_id']}] {row['regulator']} - {row['domain']} (Drift Score: {row['drift_score']:.2f})", expanded=(idx==0)):
                st.markdown(f"**Priority**: <span class='{badge_class}'>{priority_str}</span> | **Regulator**: `{row['regulator']}` | **Domain**: `{row['domain']}` | **Status**: `{row['status']}`", unsafe_allow_html=True)
                st.markdown(f"**Circular ID**: `{row['circular_id']}` | **Created At**: `{row['created_at']}`")
                
                st.markdown("### Executive Summary")
                st.info(row["summary"])

                st.markdown("### Affected Internal Policies")
                try:
                    policies = json.loads(row["affected_policies"])
                    for p in policies:
                        st.markdown(f"- 📄 **{p}**")
                except Exception:
                    st.write(row["affected_policies"])

                st.markdown("### Actionable Change Items")
                try:
                    changes = json.loads(row["change_list"])
                    for c in changes:
                        st.markdown(f"- ✅ {c}")
                except Exception:
                    st.write(row["change_list"])

